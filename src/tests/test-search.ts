import assert from "node:assert/strict";
import fs from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { Client } from "@modelcontextprotocol/sdk/client/index.js";
import { McpServer } from "@modelcontextprotocol/sdk/server/mcp.js";
import { InMemoryTransport } from "@modelcontextprotocol/sdk/inMemory.js";
import { CallToolResultSchema } from "@modelcontextprotocol/sdk/types.js";
import { registerSearchTools } from "../search-tools.js";

const root = await fs.mkdtemp(path.join(os.tmpdir(), "mcp-search-"));
const server = new McpServer({ name: "search-test", version: "1" });
registerSearchTools(server, 128 * 1024);
const client = new Client({ name: "search-test", version: "1" });
const [a, b] = InMemoryTransport.createLinkedPair();
try {
  await server.connect(a);
  await client.connect(b);
  await fs.mkdir(path.join(root, "src"));
  await fs.mkdir(path.join(root, ".git"));
  await fs.mkdir(path.join(root, ".hidden"));
  await fs.writeFile(path.join(root, ".gitignore"), "ignored.ts\n");
  await fs.writeFile(path.join(root, "ignored.ts"), "Needle\n");
  await fs.writeFile(path.join(root, ".hidden", "secret.ts"), "Needle\n");
  await fs.writeFile(path.join(root, "src", "a.ts"), "Needle\nneedle\na.b\naXb\n雪☃\n");
  await fs.writeFile(path.join(root, "src", "b.js"), "Needle\n");
  await fs.writeFile(path.join(root, "src", "a: spaced.ts"), "Needle\n");
  await fs.writeFile(path.join(root, "binary"), Buffer.from("\0Needle\0"));
  const call = async (name: string, args: Record<string, unknown>, error = false) => {
    const result = CallToolResultSchema.parse(await client.callTool({ name, arguments: { path: root, ...args } }));
    assert.equal(Boolean(result.isError), error, JSON.stringify(result));
    return result.content.map((item) => item.type === "text" ? item.text : "").join("\n");
  };
  const tools = (await client.listTools()).tools;
  assert.deepEqual(tools.map((tool) => tool.name).sort(), ["glob", "grep"]);
  for (const tool of tools) assert.equal(tool.annotations?.readOnlyHint, true);
  const files = await call("glob", { pattern: "**/*.ts" });
  assert.ok(files.includes(path.join(root, "src", "a.ts")));
  assert.ok(files.includes("a: spaced.ts"));
  assert.ok(!files.includes("secret.ts"));
  assert.ok(!files.includes("ignored.ts"));
  assert.deepEqual(files.split("\n"), files.split("\n").sort());
  assert.ok((await call("glob", { pattern: "**/*.ts", hidden: true })).includes("secret.ts"));
  assert.ok(!(await call("glob", { pattern: "**/*.ts", hidden: true })).includes("ignored.ts"));
  assert.match(await call("glob", { pattern: "**/*.ts", limit: 1 }), /Results truncated/);
  assert.match(await call("grep", { pattern: "Needle", include: "*.ts" }), /a\.ts:1: Needle/);
  const matches = await call("grep", { pattern: "Needle" });
  assert.ok(!matches.includes("a.ts:2:"));
  assert.ok(!matches.includes("secret.ts"));
  assert.ok(!matches.includes("ignored.ts"));
  assert.ok(!matches.includes(`${path.join(root, "binary")}:`));
  assert.match(await call("grep", { pattern: "Needle", caseSensitive: false }), /a\.ts:2: needle/);
  const literal = await call("grep", { pattern: "a.b", literal: true });
  assert.match(literal, /a\.ts:3: a\.b/);
  assert.ok(!literal.includes("aXb"));
  assert.match(await call("grep", { pattern: "a.b" }), /aXb/);
  assert.match(await call("grep", { pattern: "雪☃" }), /a\.ts:5: 雪☃/);
  const contextual = await call("grep", { pattern: "a.b", literal: true, context: 1 });
  assert.match(contextual, /a\.ts-2- needle/);
  assert.match(contextual, /a\.ts:3: a\.b/);
  assert.match(contextual, /a\.ts-4- aXb/);
  assert.ok(!contextual.includes("a.ts-5-"));
  const before = await call("grep", { pattern: "a.b", literal: true, before: 2 });
  assert.match(before, /a\.ts-1- Needle/);
  assert.ok(!before.includes("a.ts-4-"));
  const after = await call("grep", { pattern: "a.b", literal: true, context: 2, before: 0 });
  assert.ok(!after.includes("a.ts-2-"));
  assert.match(after, /a\.ts-5- 雪☃/);
  assert.match(await call("grep", { pattern: "a.b", literal: true, context: 2, limit: 2 }), /Results truncated/);
  await call("grep", { pattern: "x", context: -1 }, true);
  assert.match(await call("grep", { pattern: "Needle", path: path.join(root, "src", "a.ts") }), /a\.ts:1:/);
  assert.match(await call("grep", { pattern: "Needle", limit: 1 }), /Results truncated/);
  assert.equal(await call("grep", { pattern: "no-such-match" }), "No matches found.");
  assert.equal(await call("glob", { pattern: "**/*.absent" }), "No matches found.");
  await call("grep", { pattern: "[" }, true);
  await call("grep", { pattern: "Needle", path: path.join(root, "absent") }, true);
  await call("glob", { pattern: "*", path: path.join(root, "src", "a.ts") }, true);
  await call("grep", { pattern: "x", limit: 0 }, true);
  await call("glob", { pattern: "*", limit: -1 }, true);
  console.log("search MCP tests passed (schemas, globs, ignores, regex, literal, case, limits, errors)");
} finally {
  await client.close();
  await server.close();
  await fs.rm(root, { recursive: true, force: true });
}
